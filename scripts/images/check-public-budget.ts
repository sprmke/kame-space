#!/usr/bin/env bun
/**
 * Public image budget guard.
 *
 * A new 400 KB PNG in `ui/public` costs every guest on a slow connection, and nothing in the
 * build fails for it. This check does: any raster file over the limit must be either shrunk or
 * listed as an intentional exception with a reason.
 *
 * Usage: `bun run images:budget -- --check` (CI) or without `--check` for a report.
 */

import { readdirSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');
const uiPublic = join(root, 'ui/public');
const checkMode = process.argv.includes('--check');

const LIMIT_BYTES = 200 * 1024;

/** Directories that ship marketing art and are worth watching. */
const SCANNED_DIRS = ['marketing', 'images', 'brand', 'avatars'];

const RASTER_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif']);

/**
 * Files that are intentionally over budget. Each needs a reason: PWA install assets are
 * generated by the icon script at fixed sizes, and the mascot loops are video posters.
 */
const ALLOWLIST = new Map<string, string>([
  ['icons/icon-512.png', 'PWA install icon; size is fixed by the manifest'],
  ['icons/maskable-512.png', 'PWA maskable icon; size is fixed by the manifest'],
  ['icons/apple-touch-icon.png', 'iOS home-screen icon; fixed size'],
  ['brand/kame-space-mark-2048.png', 'Print and OAuth source art; never loaded by a page'],
]);

type Oversized = { path: string; kb: number; reason?: string };

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const oversized: Oversized[] = [];
for (const dir of SCANNED_DIRS) {
  const full = join(uiPublic, dir);
  let files: string[] = [];
  try {
    files = walk(full);
  } catch {
    continue;
  }
  for (const file of files) {
    const dot = file.lastIndexOf('.');
    if (dot === -1 || !RASTER_EXT.has(file.slice(dot).toLowerCase())) continue;
    const size = statSync(file).size;
    if (size <= LIMIT_BYTES) continue;
    const relative = file.slice(uiPublic.length + 1);
    oversized.push({
      path: relative,
      kb: Math.round(size / 1024),
      reason: ALLOWLIST.get(relative),
    });
  }
}

const unlisted = oversized.filter((file) => !file.reason);

for (const file of oversized) {
  const tag = file.reason ? 'allowed' : 'OVER';
  console.log(`${tag.padEnd(8)} ${String(file.kb).padStart(4)} KB  ${file.path}${file.reason ? `  (${file.reason})` : ''}`);
}

if (unlisted.length > 0) {
  console.error(
    `\nimages:budget ${checkMode ? 'FAILED' : 'report'} — ${unlisted.length} file(s) over ${LIMIT_BYTES / 1024} KB with no allowlist reason.`
  );
  console.error('Shrink them with `node scripts/media/generate-hero-variants.mjs` (hero) or a one-off sharp pass, or add a reason to ALLOWLIST.');
  if (checkMode) process.exit(1);
} else {
  console.log(`\nimages:budget OK — no unlisted public raster over ${LIMIT_BYTES / 1024} KB.`);
}
