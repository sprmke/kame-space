#!/usr/bin/env bun
/**
 * Regenerate `ui/public/robots.txt` from `ROBOTS_DISALLOW`.
 *
 * The file is the fallback served when the Vercel middleware is not running (local preview,
 * a CDN that served a cached asset before the middleware existed). It must never drift from
 * the dynamic version; `check:seo-routes` fails CI when it does.
 *
 * Run: `bun run seo:generate-robots`
 */

import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildRobotsTxt, DEFAULT_INDEXABLE_HOSTS } from '../../ui/src/lib/seo/seoMeta';
import { PRODUCTION_SITE_ORIGIN } from '../../ui/src/lib/seo/siteOrigin';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');
const target = join(root, 'ui/public/robots.txt');

const header = `# Generated by scripts/seo/generate-robots.ts from
# ui/src/lib/seo/publicRoutes.ts#ROBOTS_DISALLOW. Do not edit by hand.
# The middleware serves the same rules with a deployment-specific Sitemap line.
`;

const body = buildRobotsTxt(
  PRODUCTION_SITE_ORIGIN,
  DEFAULT_INDEXABLE_HOSTS,
  PRODUCTION_SITE_ORIGIN
);

writeFileSync(target, `${header}${body}`, 'utf8');
console.log(`Wrote ${target.replace(`${root}/`, '')}`);
